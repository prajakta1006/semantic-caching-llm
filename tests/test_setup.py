def test_pipeline_basic_query_flow():
    """Test pipeline processes query, caches on miss, and hits on repeat."""
    pipeline = SemanticCachingPipeline()

    # Query 1: Initial query -> Cache Miss -> Generated by LLM -> Stored in Cache
    resp1 = pipeline.process_query("What is machine learning?")
    assert resp1.source == "llm"
    assert resp1.decision.route == "DIRECT_LLM"
    assert "Machine learning" in resp1.response_text
    assert pipeline.cache.size() == 1

    # Query 2: Repeated query -> Cache Hit
    resp2 = pipeline.process_query("What is machine learning?")
    assert resp2.source == "cache"
    assert resp2.decision.route == "CACHE_HIT"
    assert resp2.response_text == resp1.response_text

    # Verify metrics accumulated
    metrics = pipeline.evaluator.get_metrics()
    assert metrics.total_queries == 2
    assert metrics.cache_hits == 1
    assert metrics.cache_misses == 1
    assert metrics.hit_rate == 0.5
