def test_data_models_instantiation():
    """Test creating instances of all core data models."""
    req = QueryRequest(query="test query", session_id="sess_123")
    assert req.query == "test query"
    assert req.session_id == "sess_123"

    entry = CacheEntry(query="test query", response="cached answer", similarity_score=0.95)
    assert entry.response == "cached answer"
    assert entry.similarity_score == 0.95

    dec = DecisionResult(route="CACHE_HIT", estimated_cost=0.0, confidence=0.95)
    assert dec.route == "CACHE_HIT"

    llm_resp = LLMResponse(text="llm answer", model_name="mock-llm-v1", tokens_used=10)
    assert llm_resp.text == "llm answer"

    pipe_resp = PipelineResponse(
        query="test",
        response_text="answer",
        source="cache",
        similarity_score=0.95,
        decision=dec,
        latency_ms=1.5,
    )
    assert pipe_resp.source == "cache"
    assert pipe_resp.latency_ms == 1.5

    metrics = EvaluationMetrics(total_queries=1, cache_hits=1, hit_rate=1.0)
    assert metrics.hit_rate == 1.0


